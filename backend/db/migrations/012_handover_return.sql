-- 1. Tambah kolom odometer_km pada tabel motorcycles
ALTER TABLE motorcycles ADD COLUMN IF NOT EXISTS odometer_km INTEGER DEFAULT NULL CONSTRAINT chk_motorcycles_odometer CHECK (odometer_km IS NULL OR odometer_km >= 0);

-- 2. Tabel booking_handovers
CREATE TABLE IF NOT EXISTS booking_handovers (
  booking_id INTEGER PRIMARY KEY REFERENCES bookings(id) ON DELETE CASCADE,
  odometer_start INTEGER NOT NULL CONSTRAINT chk_handovers_odometer_start CHECK (odometer_start >= 0),
  fuel_start VARCHAR(30) NOT NULL CONSTRAINT chk_handovers_fuel_start CHECK (fuel_start IN ('empty', 'quarter', 'half', 'three_quarter', 'full', 'kosong', '1/4', '1/2', '3/4', 'penuh')),
  notes TEXT DEFAULT '',
  documents_checked BOOLEAN NOT NULL CONSTRAINT chk_handovers_documents_checked CHECK (documents_checked = true),
  deposit_received BOOLEAN NOT NULL CONSTRAINT chk_handovers_deposit_received CHECK (deposit_received = true),
  handed_over_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  handed_over_by INTEGER REFERENCES users(id) ON DELETE SET NULL
);

-- 3. Tabel booking_returns
CREATE TABLE IF NOT EXISTS booking_returns (
  booking_id INTEGER PRIMARY KEY REFERENCES bookings(id) ON DELETE CASCADE,
  odometer_end INTEGER NOT NULL CONSTRAINT chk_returns_odometer_end CHECK (odometer_end >= 0),
  fuel_end VARCHAR(30) NOT NULL CONSTRAINT chk_returns_fuel_end CHECK (fuel_end IN ('empty', 'quarter', 'half', 'three_quarter', 'full', 'kosong', '1/4', '1/2', '3/4', 'penuh')),
  notes TEXT DEFAULT '',
  returned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  late_minutes INTEGER NOT NULL DEFAULT 0 CONSTRAINT chk_returns_late_minutes CHECK (late_minutes >= 0),
  late_fee INTEGER NOT NULL DEFAULT 0 CONSTRAINT chk_returns_late_fee CHECK (late_fee >= 0),
  damage_fee INTEGER NOT NULL DEFAULT 0 CONSTRAINT chk_returns_damage_fee CHECK (damage_fee >= 0),
  other_fee INTEGER NOT NULL DEFAULT 0 CONSTRAINT chk_returns_other_fee CHECK (other_fee >= 0),
  deposit_snapshot INTEGER NOT NULL DEFAULT 200000 CONSTRAINT chk_returns_deposit_snapshot CHECK (deposit_snapshot >= 0),
  deposit_refund INTEGER NOT NULL DEFAULT 0 CONSTRAINT chk_returns_deposit_refund_nonneg CHECK (deposit_refund >= 0),
  amount_due INTEGER NOT NULL DEFAULT 0 CONSTRAINT chk_returns_amount_due_nonneg CHECK (amount_due >= 0),
  deposit_refunded_at TIMESTAMPTZ DEFAULT NULL,
  deposit_refunded_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  received_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT chk_returns_consistency_refund CHECK (deposit_refund = GREATEST(0, deposit_snapshot - (late_fee + damage_fee + other_fee))),
  CONSTRAINT chk_returns_consistency_amount_due CHECK (amount_due = GREATEST(0, (late_fee + damage_fee + other_fee) - deposit_snapshot)),
  CONSTRAINT chk_returns_deposit_refunded_rule CHECK (deposit_refunded_at IS NULL OR deposit_refund > 0)
);

-- 4. Tabel booking_notes
CREATE TABLE IF NOT EXISTS booking_notes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  author_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  note TEXT NOT NULL CONSTRAINT chk_booking_notes_length CHECK (char_length(note) <= 1000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 5. Trigger validasi status booking saat Handover
CREATE OR REPLACE FUNCTION trg_validate_handover_status()
RETURNS TRIGGER AS $$
DECLARE
  b_status VARCHAR(30);
BEGIN
  SELECT status INTO b_status FROM bookings WHERE id = NEW.booking_id;
  IF b_status IS NULL THEN
    RAISE EXCEPTION 'Booking #% tidak ditemukan', NEW.booking_id USING ERRCODE = 'foreign_key_violation';
  END IF;
  IF b_status <> 'confirmed' THEN
    RAISE EXCEPTION 'Handover hanya diizinkan untuk booking berstatus "confirmed" (status saat ini: "%")', b_status
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_check_handover_booking_status ON booking_handovers;
CREATE TRIGGER trg_check_handover_booking_status
BEFORE INSERT ON booking_handovers
FOR EACH ROW EXECUTE FUNCTION trg_validate_handover_status();

-- 6. Trigger validasi status booking dan konsistensi odometer lintas tabel saat Return
CREATE OR REPLACE FUNCTION trg_validate_return_status_and_odometer()
RETURNS TRIGGER AS $$
DECLARE
  b_status VARCHAR(30);
  m_id INTEGER;
  odo_start INTEGER;
BEGIN
  SELECT status, motorcycle_id INTO b_status, m_id FROM bookings WHERE id = NEW.booking_id;
  IF b_status IS NULL THEN
    RAISE EXCEPTION 'Booking #% tidak ditemukan', NEW.booking_id USING ERRCODE = 'foreign_key_violation';
  END IF;
  IF b_status <> 'active' THEN
    RAISE EXCEPTION 'Pengembalian hanya diizinkan untuk booking berstatus "active" (status saat ini: "%")', b_status
      USING ERRCODE = 'check_violation';
  END IF;

  SELECT odometer_start INTO odo_start FROM booking_handovers WHERE booking_id = NEW.booking_id;
  IF odo_start IS NOT NULL AND NEW.odometer_end < odo_start THEN
    RAISE EXCEPTION 'Odometer akhir (% km) tidak boleh lebih kecil dari odometer awal (% km)', NEW.odometer_end, odo_start
      USING ERRCODE = 'check_violation';
  END IF;

  -- Update odometer armada motor secara otomatis
  IF m_id IS NOT NULL THEN
    UPDATE motorcycles SET odometer_km = NEW.odometer_end, updated_at = now() WHERE id = m_id;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_check_return_booking_status ON booking_returns;
CREATE TRIGGER trg_check_return_booking_status
BEFORE INSERT ON booking_returns
FOR EACH ROW EXECUTE FUNCTION trg_validate_return_status_and_odometer();
