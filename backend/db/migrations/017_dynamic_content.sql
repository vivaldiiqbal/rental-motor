-- Catatan desain:
-- * updated_by / created_by SENGAJA tidak memakai FOREIGN KEY ke users, agar
--   TRUNCATE users ... CASCADE (mis. pada seed tes) tidak ikut menghapus konten.
--   Identitas editor yang andal tercatat di audit_logs.
-- * Tidak ada seed baris di sini: bila tabel kosong, aplikasi memakai konten
--   default netral dari kode (src/config/contentDefaults.js) sebagai fallback.

CREATE TABLE IF NOT EXISTS pages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200),
  body TEXT NOT NULL DEFAULT '' CHECK (char_length(body) <= 50000),
  version INTEGER NOT NULL DEFAULT 1 CHECK (version >= 1),
  is_published BOOLEAN NOT NULL DEFAULT true,
  updated_by INTEGER,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS page_versions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_id INTEGER NOT NULL REFERENCES pages(id) ON DELETE CASCADE,
  version INTEGER NOT NULL CHECK (version >= 1),
  title TEXT NOT NULL,
  body TEXT NOT NULL DEFAULT '',
  change_note TEXT,
  created_by INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT page_versions_page_version_key UNIQUE (page_id, version)
);

CREATE INDEX IF NOT EXISTS idx_page_versions_page_id ON page_versions (page_id, version DESC);

CREATE TABLE IF NOT EXISTS faqs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question TEXT NOT NULL CHECK (char_length(question) BETWEEN 1 AND 300),
  answer TEXT NOT NULL CHECK (char_length(answer) BETWEEN 1 AND 5000),
  sort_order INTEGER NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT true,
  updated_by INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_faqs_active_order ON faqs (is_active, sort_order, id);

CREATE TABLE IF NOT EXISTS content_blocks (
  key TEXT PRIMARY KEY CHECK (key ~ '^[a-zA-Z][a-zA-Z0-9_]*$'),
  value JSONB NOT NULL,
  updated_by INTEGER,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

