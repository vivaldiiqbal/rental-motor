-- 5. Pastikan is_active, updated_at, dan trigger set_updated_at pada addons, pickup_locations, maintenance_blocks
ALTER TABLE addons ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now();
