-- 1. Tabel audit_logs (append-only)
CREATE TABLE IF NOT EXISTS audit_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  actor_role VARCHAR(30) NOT NULL,
  action VARCHAR(100) NOT NULL,
  entity_type VARCHAR(50) NOT NULL,
  entity_id VARCHAR(100) DEFAULT NULL,
  before JSONB DEFAULT NULL,
  after JSONB DEFAULT NULL,
  ip VARCHAR(50) DEFAULT NULL,
  user_agent TEXT DEFAULT NULL,
  at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Index performa audit logs
CREATE INDEX IF NOT EXISTS idx_audit_logs_at ON audit_logs (at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_actor_at ON audit_logs (actor_id, at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_entity_at ON audit_logs (entity_type, entity_id, at DESC);

-- Trigger penolakan UPDATE dan DELETE pada tabel audit_logs
CREATE OR REPLACE FUNCTION trg_prevent_audit_logs_modification()
RETURNS TRIGGER AS $$
BEGIN
  RAISE EXCEPTION 'Tabel audit_logs bersifat append-only: operasi UPDATE dan DELETE dilarang keras demi integritas forensik'
    USING ERRCODE = 'restrict_violation';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_audit_logs_no_update_delete ON audit_logs;
CREATE TRIGGER trg_audit_logs_no_update_delete
BEFORE UPDATE OR DELETE ON audit_logs
FOR EACH ROW EXECUTE FUNCTION trg_prevent_audit_logs_modification();

