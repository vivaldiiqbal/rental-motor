ALTER TABLE reviews ADD COLUMN IF NOT EXISTS hidden_by INTEGER REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE reviews ADD COLUMN IF NOT EXISTS hidden_at TIMESTAMPTZ DEFAULT NULL;
ALTER TABLE reviews ADD COLUMN IF NOT EXISTS hidden_reason TEXT DEFAULT NULL;

-- 3. Reviewer dokumen pengguna (user_documents)
ALTER TABLE user_documents ADD COLUMN IF NOT EXISTS reviewed_by INTEGER REFERENCES users(id) ON DELETE SET NULL;

-- 4. Metadata pencatat jadwal servis (maintenance_blocks)
ALTER TABLE maintenance_blocks ADD COLUMN IF NOT EXISTS created_by INTEGER REFERENCES users(id) ON DELETE SET NULL;
