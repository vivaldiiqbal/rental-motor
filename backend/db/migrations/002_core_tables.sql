-- 1. users
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(255) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'customer',
  emergency_contact_name VARCHAR(100) DEFAULT NULL,
  emergency_contact_phone VARCHAR(30) DEFAULT NULL,
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_users_role CHECK (role IN ('customer', 'admin'))
);

-- 2. user_documents
-- Catatan: Status 'not_uploaded' tidak disimpan di tabel; diturunkan pada mapper bila baris tidak ada.
CREATE TABLE IF NOT EXISTS user_documents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type VARCHAR(10) NOT NULL,
  stored_name VARCHAR(255) NOT NULL,
  mime_type VARCHAR(100) NOT NULL,
  size_bytes INTEGER NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  reviewer_note TEXT DEFAULT NULL,
  uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  verified_at TIMESTAMPTZ DEFAULT NULL,
  CONSTRAINT chk_user_documents_type CHECK (type IN ('ktp', 'sim')),
  CONSTRAINT chk_user_documents_status CHECK (status IN ('pending', 'verified', 'rejected')),
  CONSTRAINT uq_user_documents_user_type UNIQUE (user_id, type)
);

-- 3. motorcycles
CREATE TABLE IF NOT EXISTS motorcycles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(100) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  brand VARCHAR(50) NOT NULL,
  type VARCHAR(30) NOT NULL,
  cc INTEGER NOT NULL,
  year INTEGER NOT NULL,
  color VARCHAR(50) NOT NULL,
  transmission VARCHAR(20) NOT NULL,
  fuel_capacity NUMERIC(4, 1) NOT NULL DEFAULT 4.2,
  price_per_day INTEGER NOT NULL,
  deposit INTEGER NOT NULL DEFAULT 200000,
  description TEXT DEFAULT '',
  plate_number VARCHAR(30) NOT NULL UNIQUE,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  rating_avg NUMERIC(3, 2) NOT NULL DEFAULT 0.00,
  rating_count INTEGER NOT NULL DEFAULT 0,
  rating_1 INTEGER NOT NULL DEFAULT 0,
  rating_2 INTEGER NOT NULL DEFAULT 0,
  rating_3 INTEGER NOT NULL DEFAULT 0,
  rating_4 INTEGER NOT NULL DEFAULT 0,
  rating_5 INTEGER NOT NULL DEFAULT 0,
  rental_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_motorcycles_type CHECK (type IN ('matic', 'manual', 'sport', 'trail')),
  CONSTRAINT chk_motorcycles_status CHECK (status IN ('active', 'maintenance', 'inactive')),
  CONSTRAINT chk_motorcycles_price CHECK (price_per_day > 0),
  CONSTRAINT chk_motorcycles_deposit CHECK (deposit >= 0),
  CONSTRAINT chk_motorcycles_stats CHECK (
    rating_avg >= 0 AND rating_count >= 0 AND
    rating_1 >= 0 AND rating_2 >= 0 AND rating_3 >= 0 AND rating_4 >= 0 AND rating_5 >= 0 AND
    rental_count >= 0
  )
);

-- 4. motorcycle_images
CREATE TABLE IF NOT EXISTS motorcycle_images (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  motorcycle_id INTEGER NOT NULL REFERENCES motorcycles(id) ON DELETE CASCADE,
  url TEXT NOT NULL,
  position INTEGER NOT NULL DEFAULT 0,
  is_primary BOOLEAN NOT NULL DEFAULT false
);

-- UNIQUE partial: satu is_primary per motor
CREATE UNIQUE INDEX IF NOT EXISTS idx_motorcycle_images_primary
ON motorcycle_images (motorcycle_id)
WHERE is_primary = true;

-- 5. motorcycle_features
CREATE TABLE IF NOT EXISTS motorcycle_features (
  motorcycle_id INTEGER NOT NULL REFERENCES motorcycles(id) ON DELETE CASCADE,
  feature TEXT NOT NULL,
  PRIMARY KEY (motorcycle_id, feature)
);

-- 6. maintenance_blocks
CREATE TABLE IF NOT EXISTS maintenance_blocks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  motorcycle_id INTEGER NOT NULL REFERENCES motorcycles(id) ON DELETE CASCADE,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  reason TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_maintenance_blocks_dates CHECK (end_date > start_date),
  CONSTRAINT no_overlapping_maintenance EXCLUDE USING gist (
    motorcycle_id WITH =,
    daterange(start_date, end_date, '[)') WITH &&
  )
);

-- 7. pickup_locations
CREATE TABLE IF NOT EXISTS pickup_locations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  address TEXT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT true,
  sort_order INTEGER NOT NULL DEFAULT 0
);

-- 8. addons
CREATE TABLE IF NOT EXISTS addons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  price_per_day INTEGER NOT NULL CHECK (price_per_day >= 0),
  is_active BOOLEAN NOT NULL DEFAULT true
);
