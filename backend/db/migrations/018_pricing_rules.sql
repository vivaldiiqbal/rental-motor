-- 1. Tabel pricing_rules: Aturan tambahan harga (weekend, seasonal, holiday, surge, dsb.)
CREATE TABLE IF NOT EXISTS pricing_rules (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK (char_length(name) BETWEEN 2 AND 150),
  rule_type TEXT NOT NULL CHECK (rule_type IN ('weekend', 'seasonal', 'holiday', 'custom')),
  rate_type TEXT NOT NULL CHECK (rate_type IN ('percentage', 'fixed', 'multiplier')),
  rate_value NUMERIC(12, 2) NOT NULL CHECK (rate_value >= 0),
  scope TEXT NOT NULL DEFAULT 'all' CHECK (scope IN ('all', 'motor_type', 'motorcycle')),
  target_motor_type TEXT CHECK (target_motor_type IS NULL OR target_motor_type IN ('matic', 'manual', 'sport', 'trail', 'electric')),
  target_motorcycle_id INTEGER,
  start_date DATE,
  end_date DATE,
  priority INTEGER NOT NULL DEFAULT 10 CHECK (priority >= 0),
  is_active BOOLEAN NOT NULL DEFAULT true,
  description TEXT DEFAULT '',
  updated_by INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT check_seasonal_dates CHECK (
    rule_type NOT IN ('seasonal', 'holiday') OR (start_date IS NOT NULL AND end_date IS NOT NULL AND end_date >= start_date)
  )
);

CREATE INDEX IF NOT EXISTS idx_pricing_rules_active_priority ON pricing_rules (is_active, priority DESC, id ASC);
CREATE INDEX IF NOT EXISTS idx_pricing_rules_dates ON pricing_rules (start_date, end_date) WHERE start_date IS NOT NULL;

-- 2. Tabel discount_tiers: Diskon durasi sewa bertingkat (mis. 3 hari -> 5%, 7 hari -> 10%)
CREATE TABLE IF NOT EXISTS discount_tiers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  min_days INTEGER NOT NULL UNIQUE CHECK (min_days >= 1),
  discount_percent NUMERIC(5, 2) NOT NULL CHECK (discount_percent >= 0 AND discount_percent <= 100),
  description TEXT DEFAULT '',
  is_active BOOLEAN NOT NULL DEFAULT true,
  updated_by INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_discount_tiers_days ON discount_tiers (min_days ASC);

-- 3. Tambah kolom pricing_snapshot pada tabel bookings jika belum ada
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS pricing_snapshot JSONB DEFAULT NULL;

