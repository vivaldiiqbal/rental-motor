-- 9. promo_codes
CREATE TABLE IF NOT EXISTS promo_codes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50) NOT NULL,
  type VARCHAR(20) NOT NULL,
  value INTEGER NOT NULL,
  max_discount INTEGER DEFAULT NULL,
  min_days INTEGER NOT NULL DEFAULT 1,
  weekend_only BOOLEAN NOT NULL DEFAULT false,
  valid_from DATE NOT NULL DEFAULT CURRENT_DATE,
  valid_until DATE NOT NULL,
  usage_limit INTEGER DEFAULT NULL,
  used_count INTEGER NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_promo_codes_type CHECK (type IN ('percent', 'fixed')),
  CONSTRAINT chk_promo_codes_value CHECK (value > 0),
  CONSTRAINT chk_promo_codes_usage CHECK (usage_limit IS NULL OR used_count <= usage_limit)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_promo_codes_upper ON promo_codes (upper(code));

-- 10. bookings
CREATE TABLE IF NOT EXISTS bookings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_code VARCHAR(50) NOT NULL UNIQUE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  motorcycle_id INTEGER NOT NULL REFERENCES motorcycles(id) ON DELETE RESTRICT,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  total_days INTEGER NOT NULL,
  pickup_time TIME NOT NULL DEFAULT '09:00',
  pickup_location_id INTEGER REFERENCES pickup_locations(id) ON DELETE SET NULL,
  pickup_location_text TEXT DEFAULT '',
  delivery_pickup BOOLEAN NOT NULL DEFAULT false,
  delivery_dropoff BOOLEAN NOT NULL DEFAULT false,
  renter_name VARCHAR(100) NOT NULL,
  renter_phone VARCHAR(30) NOT NULL,
  renter_email VARCHAR(255) NOT NULL,
  emergency_contact_name VARCHAR(100) DEFAULT NULL,
  emergency_contact_phone VARCHAR(30) DEFAULT NULL,
  notes TEXT DEFAULT '',
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  expires_at TIMESTAMPTZ DEFAULT NULL,
  price_per_day INTEGER NOT NULL,
  subtotal INTEGER NOT NULL,
  duration_discount INTEGER NOT NULL DEFAULT 0,
  promo_code_id INTEGER REFERENCES promo_codes(id) ON DELETE SET NULL,
  promo_discount INTEGER NOT NULL DEFAULT 0,
  addons_total INTEGER NOT NULL DEFAULT 0,
  delivery_total INTEGER NOT NULL DEFAULT 0,
  rental_total INTEGER NOT NULL,
  deposit INTEGER NOT NULL DEFAULT 0,
  grand_total INTEGER NOT NULL,
  refund_amount INTEGER NOT NULL DEFAULT 0,
  cancel_reason TEXT DEFAULT NULL,
  cancelled_at TIMESTAMPTZ DEFAULT NULL,
  paid_at TIMESTAMPTZ DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_bookings_status CHECK (status IN ('pending', 'confirmed', 'active', 'completed', 'cancelled', 'expired')),
  CONSTRAINT chk_bookings_days_range CHECK (total_days >= 1 AND total_days <= 30),
  CONSTRAINT chk_bookings_date_order CHECK (end_date > start_date),
  CONSTRAINT chk_bookings_total_days CHECK (total_days = (end_date - start_date)),
  CONSTRAINT chk_bookings_rental_total CHECK (rental_total = (subtotal - duration_discount - promo_discount + addons_total + delivery_total)),
  CONSTRAINT chk_bookings_grand_total CHECK (grand_total = (rental_total + deposit)),
  CONSTRAINT chk_bookings_refund_amount CHECK (refund_amount >= 0 AND refund_amount <= rental_total),
  CONSTRAINT no_double_booking EXCLUDE USING gist (
    motorcycle_id WITH =,
    daterange(start_date, end_date, '[)') WITH &&
  ) WHERE (status IN ('pending', 'confirmed', 'active'))
);

-- 11. booking_items
CREATE TABLE IF NOT EXISTS booking_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  kind VARCHAR(30) NOT NULL,
  label VARCHAR(150) NOT NULL,
  unit_price INTEGER NOT NULL DEFAULT 0,
  quantity INTEGER NOT NULL DEFAULT 1,
  days INTEGER NOT NULL DEFAULT 1,
  amount INTEGER NOT NULL,
  CONSTRAINT chk_booking_items_kind CHECK (kind IN ('rental', 'addon', 'delivery', 'discount_duration', 'discount_promo', 'deposit'))
);

-- 12. booking_timeline
CREATE TABLE IF NOT EXISTS booking_timeline (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  status VARCHAR(30) NOT NULL,
  note TEXT DEFAULT '',
  actor VARCHAR(20) NOT NULL,
  at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_booking_timeline_actor CHECK (actor IN ('customer', 'system', 'admin', 'payment'))
);

-- 13. promo_redemptions
CREATE TABLE IF NOT EXISTS promo_redemptions (
  booking_id INTEGER PRIMARY KEY REFERENCES bookings(id) ON DELETE CASCADE,
  promo_id INTEGER NOT NULL REFERENCES promo_codes(id) ON DELETE RESTRICT,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  discount_amount INTEGER NOT NULL CHECK (discount_amount >= 0),
  redeemed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  released_at TIMESTAMPTZ DEFAULT NULL
);

-- 14. payments
CREATE TABLE IF NOT EXISTS payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE RESTRICT,
  method VARCHAR(30) NOT NULL,
  provider VARCHAR(30) NOT NULL DEFAULT 'simulation',
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  amount INTEGER NOT NULL,
  gateway_ref VARCHAR(150) DEFAULT NULL,
  instructions JSONB DEFAULT '{}'::jsonb,
  paid_at TIMESTAMPTZ DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_payments_method CHECK (method IN ('bank_transfer', 'ewallet', 'qris')),
  CONSTRAINT chk_payments_provider CHECK (provider IN ('simulation', 'midtrans')),
  CONSTRAINT chk_payments_status CHECK (status IN ('pending', 'paid', 'failed', 'expired', 'refunded', 'needs_refund')),
  CONSTRAINT chk_payments_amount CHECK (amount > 0)
);

-- UNIQUE INDEX parsial: satu payment berstatus pending per booking
CREATE UNIQUE INDEX IF NOT EXISTS idx_payments_one_pending
ON payments (booking_id)
WHERE (status = 'pending');

-- UNIQUE (provider, gateway_ref) WHERE gateway_ref IS NOT NULL
CREATE UNIQUE INDEX IF NOT EXISTS idx_payments_provider_gateway_ref
ON payments (provider, gateway_ref)
WHERE (gateway_ref IS NOT NULL);

-- 15. payment_events
CREATE TABLE IF NOT EXISTS payment_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider VARCHAR(30) NOT NULL,
  event_id VARCHAR(150) NOT NULL,
  payload JSONB NOT NULL,
  received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  processed_at TIMESTAMPTZ DEFAULT NULL,
  result TEXT DEFAULT NULL,
  CONSTRAINT uq_payment_events_provider_event UNIQUE (provider, event_id)
);

-- 16. reviews
CREATE TABLE IF NOT EXISTS reviews (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER UNIQUE NOT NULL REFERENCES bookings(id) ON DELETE RESTRICT,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  motorcycle_id INTEGER NOT NULL REFERENCES motorcycles(id) ON DELETE RESTRICT,
  rating INTEGER NOT NULL,
  comment TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_reviews_rating CHECK (rating >= 1 AND rating <= 5),
  CONSTRAINT chk_reviews_comment CHECK (char_length(comment) <= 500)
);

-- 17. favorites
CREATE TABLE IF NOT EXISTS favorites (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  motorcycle_id INTEGER NOT NULL REFERENCES motorcycles(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, motorcycle_id)
);

-- 18. contact_messages
CREATE TABLE IF NOT EXISTS contact_messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(255) NOT NULL,
  subject VARCHAR(200) NOT NULL,
  message TEXT NOT NULL,
  ip VARCHAR(50) DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 19. idempotency_keys
CREATE TABLE IF NOT EXISTS idempotency_keys (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  key VARCHAR(100) NOT NULL,
  request_hash VARCHAR(64) DEFAULT '',
  response_status INTEGER NOT NULL,
  response_body JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, key)
);
