export const motors: Motor[] = seeds.map((s, i) => {
  const slug = slugify(s.name);
  const transmission: Transmission = s.type === 'matic' ? 'Otomatis' : 'Manual';
  return {
    id: `m${i + 1}`,
    slug,
    name: s.name,
    brand: s.brand,
    type: s.type,
    cc: s.cc,
    year: s.year,
    color: s.color,
    transmission,
    fuelCapacity: s.fuel,
    pricePerDay: s.price,
    deposit: s.price >= 200000 ? 500000 : 300000,
    description: s.description,
    features: s.features,
    images: img(slug),
    status: s.maintenance ? 'maintenance' : 'available',
    rating: s.rating,
    reviewCount: s.reviews,
    plate: s.plate,
    popularity: s.popularity,
  };
});
